package uk.scimone.diafit.mealactivity

import org.junit.Assert.*
import org.junit.Test
import uk.scimone.diafit.mealactivity.domain.*

class PersonalizationTest {
    private val slowPerson = PersonalAdjust(timeScale = 1.45, onsetShiftMin = 12.0)

    @Test fun csvOnlyNoMealsGivesNoEpisodes() {
        val w = World(slowPerson); w.generate(40)
        val none = TrainingExampleBuilder.buildAll(emptyList(), T0 + 400 * HOUR, readingsBetween = w::readingsBetween)
        assertTrue(none.examples.isEmpty())
        assertTrue(PersonalTrainer.train(none.examples) is TrainOutcome.Ineligible)
    }

    @Test fun mealsWithoutCgmStayBaseline() {
        val w = World(slowPerson); w.generate(40, dropCgm = true)
        val set = w.trainingSet()
        assertTrue(set.examples.isEmpty())
        assertTrue((set.excluded[Exclusion.NO_BASELINE] ?: 0) >= 30)
    }

    @Test fun tooFewEpisodesIsIneligible() {
        val w = World(slowPerson); w.generate(20)
        val set = w.trainingSet()
        assertEquals(20, set.examples.size)
        val r = PersonalTrainer.train(set.examples)
        assertTrue(r is TrainOutcome.Ineligible)
    }

    @Test fun enoughValidEpisodesFitAndPromote() {
        val w = World(slowPerson); w.generate(45)
        val set = w.trainingSet()
        assertTrue(set.examples.size >= 40)
        val r = PersonalTrainer.train(set.examples)
        assertTrue("expected accepted, was $r", r is TrainOutcome.Accepted)
        r as TrainOutcome.Accepted
        // Learned a slower, later absorption than the baseline (direction, not exact recovery: CGM is indirect evidence).
        // The parameters trade off (onset vs width), so compare what matters: the modelled absorption timing of a reference meal.
        val ref = MealInput(60.0, 20.0, 20.0, null, AbsorptionSpeed.MEDIUM, T0)
        fun meanTime(e: MealActivityEngine) = e.carbTiming(ref).let { (onset, scale) -> onset + ActivityParams().carbShape * scale }
        val truth = meanTime(MealActivityEngine(adjust = slowPerson)); val base = meanTime(MealActivityEngine())
        val learned = meanTime(MealActivityEngine(adjust = r.adjust))
        assertTrue("learned $learned truth $truth base $base", Math.abs(learned - truth) < Math.abs(base - truth) * 0.6)
        assertTrue(r.report.candidateHoldout!!.mae < r.report.baselineHoldout!!.mae)
        assertEquals(r.report.holdoutEpisodes, 12.coerceAtLeast(r.report.holdoutEpisodes))
    }

    @Test fun fittingIsDeterministic() {
        val w = World(slowPerson); w.generate(40)
        val ex = w.trainingSet().examples
        assertEquals(PersonalFitter.fit(ex, false), PersonalFitter.fit(ex, false))
    }

    @Test fun baselineWorldDoesNotPromoteAWorseOrEqualModel() {
        val w = World(PersonalAdjust(), noise = 8.0, seed = 7); w.generate(45)
        val r = PersonalTrainer.train(w.trainingSet().examples)
        // Data generated by the baseline itself: no candidate may be accepted unless clearly better on held-out meals.
        if (r is TrainOutcome.Accepted) assertTrue(r.report.candidateHoldout!!.mae <= r.report.baselineHoldout!!.mae * 0.95)
        else assertTrue(r is TrainOutcome.Rejected)
    }

    @Test fun pureNoiseIsRejectedOrBaselineKept() {
        val w = World(PersonalAdjust()); w.generate(45)
        val rnd = java.util.Random(3)
        val noisy = w.readings.map { it.copy(valueMgdl = 100 + rnd.nextInt(40)) }
        val set = TrainingExampleBuilder.buildAll(w.meals, T0 + 400 * HOUR) { a, b -> noisy.filter { it.timestamp in a..b } }
        val r = PersonalTrainer.train(set.examples)
        assertFalse("noise must not be promoted", r is TrainOutcome.Accepted)
    }

    @Test fun validationIsTimeOrderedWithoutLeakage() {
        val w = World(slowPerson); w.generate(45)
        val ex = w.trainingSet().examples
        val holdoutN = 12
        val train = ex.dropLast(holdoutN); val hold = ex.takeLast(holdoutN)
        assertTrue(train.maxOf { it.startUtc } < hold.minOf { it.startUtc })
        assertTrue(train.map { it.key }.intersect(hold.map { it.key }.toSet()).isEmpty())
    }

    // ---- training-example construction ----

    @Test fun cgmGapsExcludeEpisode() {
        val w = World(slowPerson); w.generate(1)
        val gappy = w.readings.filterNot { it.timestamp in (T0 + 60 * MIN)..(T0 + 150 * MIN) }
        val set = TrainingExampleBuilder.buildAll(w.meals, T0 + 20 * HOUR) { a, b -> gappy.filter { it.timestamp in a..b } }
        assertEquals(0, set.examples.size)
        assertTrue(set.excluded.keys.any { it == Exclusion.LARGE_GAP || it == Exclusion.LOW_COVERAGE })
    }

    @Test fun overlappingMealsAreHandledByPolicy() {
        val w = World(slowPerson); w.generate(1)
        val second = meal(2, T0 + 90 * MIN, 50)          // 1.5 h after the first
        val set = TrainingExampleBuilder.buildAll(w.meals + second, T0 + 20 * HOUR, readingsBetween = w::readingsBetween)
        assertEquals(0, set.examples.size) // first: next meal too soon (clean span 90 < 180); second: prior meal within 2 h
        val third = meal(3, T0 + 4 * HOUR, 50)           // far enough: first is kept with its target masked after 4 h
        val ok = TrainingExampleBuilder.buildAll(w.meals + third, T0 + 20 * HOUR, readingsBetween = w::readingsBetween)
        val first = ok.examples.single { it.startUtc == T0 }
        assertTrue(first.observed[16].isNaN()) // 240 min = next meal start: masked
        assertFalse(first.observed[8].isNaN())
    }

    @Test fun lowBaselineAndMissingMacrosAreExcluded() {
        val w = World(slowPerson); w.generate(1)
        val low = w.readings.map { if (it.timestamp <= T0) it.copy(valueMgdl = 60) else it }
        assertEquals(0, TrainingExampleBuilder.buildAll(w.meals, T0 + 20 * HOUR) { a, b -> low.filter { it.timestamp in a..b } }.examples.size)
        val noCarbs = listOf(w.meals.single().copy(carbohydrates = 5))
        assertEquals(0, TrainingExampleBuilder.buildAll(noCarbs, T0 + 20 * HOUR, readingsBetween = w::readingsBetween).examples.size)
    }

    @Test fun futureReadingsNeverMakeAnEpisodeBeforeHorizonElapsed() {
        val w = World(slowPerson); w.generate(1)
        val tooEarly = TrainingExampleBuilder.buildAll(w.meals, T0 + 3 * HOUR, readingsBetween = w::readingsBetween)
        assertEquals(0, tooEarly.examples.size)
        assertEquals(1, tooEarly.excluded[Exclusion.HORIZON_NOT_ELAPSED])
    }

    @Test fun observedTargetsAreRealReadingsNotInterpolated() {
        val w = World(slowPerson); w.generate(1)
        val sparse = w.readings.filterIndexed { i, _ -> i % 2 == 0 || true }.filter { (it.timestamp - T0) % (10 * MIN) == 0L || it.timestamp <= T0 }
        val set = TrainingExampleBuilder.buildAll(w.meals, T0 + 20 * HOUR) { a, b -> sparse.filter { it.timestamp in a..b } }
        val ex = set.examples.singleOrNull() ?: return // thin data may be excluded; never filled
        assertTrue(ex.observed.count { it.isNaN() } + ex.observed.count { !it.isNaN() } == ex.observed.size)
        assertEquals(0.0, ex.observed[0], 0.0)
    }

    @Test fun duplicateMealsCountOnce() {
        val w = World(slowPerson); w.generate(1)
        val dup = w.meals.single().copy(id = 99, sittingId = "dup")
        val set = TrainingExampleBuilder.buildAll(w.meals + dup, T0 + 20 * HOUR, readingsBetween = w::readingsBetween)
        assertTrue(set.examples.size <= 1)
    }

    @Test fun revisionIsOrderIndependentAndChangesWithData() {
        val w = World(slowPerson); w.generate(5)
        val a = w.trainingSet()
        val shuffled = TrainingExampleBuilder.buildAll(w.meals.reversed(), T0 + 400 * HOUR, readingsBetween = w::readingsBetween)
        assertEquals(a.revision, shuffled.revision)
        val edited = TrainingExampleBuilder.buildAll(w.meals.map { if (it.id == 2) it.copy(carbohydrates = it.carbohydrates + 10) else it }, T0 + 400 * HOUR, readingsBetween = w::readingsBetween)
        assertNotEquals(a.revision, edited.revision)
    }
}
